"""
workloads.py
------------
Independent and real-data workloads for Reviewer 2, comment (f).

1. Independent synthetic workloads, generated by mechanisms that differ from
   the training generator (generate_dataset.py):
     W1  weak latent context        sigma_ctx = 0.08
     W2  strong latent context      sigma_ctx = 0.24
     W3  probabilistic labels       P(urgent) = logistic((tau_true - 0.72)/0.05)
     W4  shifted modality mix       sigma ~ (0.20, 0.35, 0.45): more imaging
     W5  heavy-tailed CPU demand    Pareto(alpha = 1.5), mean matched, cap 8000
     W6  bursty arrivals            2-state MMPP, bursts at 3x the base rate
   All use a fresh seed (7) and fresh devices, so no device, item or
   parameter draw is shared with the training data.

2. Real-data workload: LoRaWAN sensor messages from a tomato farm in Parma,
   Italy (Belli et al., Mendeley Data 10.17632/35wh56287y.2; Data in Brief
   2025): one environmental station (air T/RH), three soil probes
   (moisture/EC/T at 20 cm) and three irrigation water meters, 10-min
   sampling, 29 Jun - 13 Sep 2023, ~76k messages.
   Urgency labels are derived from agronomic rules that use the stream's
   temporal context, which a per-message gateway classifier cannot observe:
     heat stress  : air T >= 35 C sustained over the current and two
                    previous readings (>= 30 min)
     water stress : soil moisture below the line's 10th percentile and
                    falling over the last hour
     flow anomaly : 10-min water increment above 1.25 x the line's 99th
                    percentile of positive increments, or flow sustained
                    for >= 6 consecutive intervals
   The device-observable breach flag is instantaneous and coarser
   (T >= 33 C; moisture below the 15th percentile; increment above the 95th
   percentile or flow for >= 3 intervals).  Deadlines follow the agronomic action class, not the label.
"""
