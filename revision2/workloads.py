def gen(n=50000, seed=7, n_dev=1200, sigma_ctx=0.16, label_mode="hard",
        modal_p=(0.50, 0.35, 0.15), cpu_mode="uniform"):
    rng = np.random.default_rng(seed)
    dev_ctx = rng.normal(0.0, sigma_ctx, n_dev)
    dev_sigma = rng.choice([0, 1, 2], n_dev, p=list(modal_p))
    dev_phi = rng.uniform(0.1, 1.0, n_dev)
    w = rng.gamma(2.0, 1.0, n_dev); w /= w.sum()
    dev = rng.choice(np.arange(n_dev), n, p=w)
    sigma = dev_sigma[dev]
    phi = np.clip(dev_phi[dev] + rng.normal(0, .03, n), 0, 1)
    rho = np.where(sigma == 2, rng.uniform(500.0, 2867.0, n), rng.uniform(0.04, 50.0, n))
    pi = (rng.random(n) < 0.08).astype(int)
    breach = (rng.random(n) < 0.28).astype(int)
    u_obs = 0.5 * breach + 0.3 * phi + 0.2 * (1.0 - rho / 2867.0)
    delta = np.clip(10.0 ** (4.2 - 4.0 * u_obs + rng.normal(0.0, 0.60, n)), 0.5, 86400.0)
    tau = compute_urgency(phi, delta, rho, breach)
    tau_true = tau + dev_ctx[dev] + rng.normal(0.0, 0.05, n)
    if label_mode == "hard":
        lab = tau_true > TAU_LABEL
    else:
        lab = rng.random(n) < 1.0 / (1.0 + np.exp(-(tau_true - TAU_LABEL) / 0.05))
    label = (lab | (pi == 1)).astype(int)
    if cpu_mode == "uniform":
        cpu = rng.uniform(100.0, 8000.0, n)
    else:   # Pareto, alpha=1.5, scaled so the mean matches 4050, capped
        x = (rng.pareto(1.5, n) + 1.0)
        cpu = np.clip(x * 1350.0, 100.0, 8000.0)
        cpu *= 4050.0 / cpu.mean()
        cpu = np.clip(cpu, 100.0, 8000.0)
    mem = rng.uniform(2.0, 512.0, n)
    psi = (tau + phi + 1.0 / (delta + 1e-6)) / 3.0
    return pd.DataFrame(dict(task_id=np.arange(n), device_id=dev, tau=tau, sigma=sigma,
                             delta_s=delta, pi=pi, rho_kb=rho, phi=phi,
                             threshold_breach=breach, cpu_demand_mips=cpu,
                             mem_demand_mb=mem, psi=psi, label=label))


