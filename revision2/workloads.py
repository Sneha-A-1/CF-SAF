def mmpp_gaps(rate, burst=3.0, on_frac=0.2, mean_on_s=2.0):
    """2-state MMPP inter-arrival generator with long-run mean rate `rate`."""
    lo = rate / (on_frac * burst + (1 - on_frac))
    hi = burst * lo
    mean_off_s = mean_on_s * (1 - on_frac) / on_frac

    def f(rng, n):
        gaps, state, left = np.empty(n), 0, rng.exponential(mean_off_s)
        for i in range(n):
            r = hi if state else lo
            g = rng.exponential(1.0 / r)
            while g > left:
                g -= left
                state ^= 1
                left = rng.exponential(mean_on_s if state else mean_off_s)
                r_new = hi if state else lo
                g = g * r / r_new
                r = r_new
            left -= g
            gaps[i] = g * 1000.0
        return gaps
    return f


