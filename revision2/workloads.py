def _num(df, cols):
    for c in cols:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    return df.dropna(subset=cols)


def load_real():
    env = pd.read_csv(f"{REAL_DIR}/stuard_environmental_data.csv", dtype=str, na_values="NULL")
    soil = pd.read_csv(f"{REAL_DIR}/stuard_soil_data.csv", dtype=str, na_values="NULL")
    wat = pd.read_csv(f"{REAL_DIR}/stuard_water_meter_data.csv", dtype=str, na_values="NULL")
    env = _num(env, ["ts_generation", "temperature", "humidity"]).sort_values("ts_generation")
    soil = _num(soil, ["ts_generation", "line", "humidity", "electrical_conductivity"]).sort_values("ts_generation")
    wat = _num(wat, ["ts_generation", "line", "current_volume"]).sort_values("ts_generation")
    rows = []
    # environmental station: heat stress
    T = env.temperature.values
    sus = (T >= 35) & (np.r_[np.nan, T[:-1]] >= 35) & (np.r_[np.nan, np.nan, T[:-2]] >= 35)
    rows.append(pd.DataFrame(dict(ts=env.ts_generation.values, stream="env0", kind="env",
                                  breach=(T >= 33).astype(int), label=sus.astype(int),
                                  sigma=1, phi0=0.6)))
    for ln, g in soil.groupby("line"):
        h = g.humidity.values
        p10, p15 = np.quantile(h, 0.10), np.quantile(h, 0.15)
        falling = np.r_[[False] * 6, h[6:] < h[:-6]]
        rows.append(pd.DataFrame(dict(ts=g.ts_generation.values, stream=f"soil{int(ln)}",
                                      kind="soil", breach=(h < p15).astype(int),
                                      label=((h < p10) & falling).astype(int),
                                      sigma=0, phi0=0.75)))
    for ln, g in wat.groupby("line"):
        v = g.current_volume.values
        dv = np.r_[0.0, np.diff(v)]
        dv[dv < 0] = 0.0
        pos = dv[dv > 0]
        p95, p99 = np.quantile(pos, 0.95), np.quantile(pos, 0.99)
        flow = dv > 0
        run = np.zeros(len(dv), int)
        for i in range(1, len(dv)):
            run[i] = run[i - 1] + 1 if flow[i] else 0
        lab = (dv > 1.25 * p99) | (run >= 6)
        rows.append(pd.DataFrame(dict(ts=g.ts_generation.values, stream=f"water{int(ln)}",
                                      kind="water",
                                      breach=((dv > p95) | (run >= 3)).astype(int),
                                      label=lab.astype(int), sigma=0, phi0=0.9)))
    return pd.concat(rows, ignore_index=True).sort_values("ts").reset_index(drop=True)


DEADLINE = {"env": 900.0, "soil": 1800.0, "water": 300.0}   # s, routine action


def real_tasks(seed=11, n=None, ts_override=None, base=None):
    """Turn real messages into CF-SAF tasks.  CPU/memory demands are drawn
    as in the synthetic generator (no real measurements exist); every other
    field comes from the real stream or from documented device properties."""
    rng = np.random.default_rng(seed)
    r = load_real() if base is None else base.copy()
    if n is not None:
        r = r.iloc[:n].copy()
    m = len(r)
    phi = np.clip(r.phi0.values + rng.normal(0, 0.03, m), 0, 1)
    rho = rng.uniform(0.011, 0.051, m)                 # LoRaWAN payload, KB
    breach = r.breach.values
    dl = np.array([DEADLINE[k] for k in r.kind.values])
    delta = np.where(breach == 1, 60.0, dl) * np.exp(rng.normal(0, 0.3, m))
    tau = compute_urgency(phi, delta, rho, breach)
    pi = np.zeros(m, int)
    cpu = rng.uniform(100.0, 8000.0, m)
    mem = rng.uniform(2.0, 512.0, m)
    psi = (tau + phi + 1.0 / (delta + 1e-6)) / 3.0
    return pd.DataFrame(dict(task_id=np.arange(m), device_id=pd.factorize(r.stream)[0],
                             ts=r.ts.values, stream=r.stream.values, tau=tau,
                             sigma=r.sigma.values, delta_s=delta, pi=pi, rho_kb=rho,
                             phi=phi, threshold_breach=breach, cpu_demand_mips=cpu,
                             mem_demand_mb=mem, psi=psi, label=r.label.values))


def real_replay(n_tasks, rate, seed, n_virtual=1200, base=None):
    """Arrival trace for scheduling: n_virtual virtual devices, each replaying
    one of the 7 real streams with a random phase (within +-1 day), with
    time compressed so the aggregate rate equals `rate`.  Returns the task
    frame (in arrival order) and the inter-arrival gaps in ms."""
    rng = np.random.default_rng(seed)
    base = real_tasks(seed=seed) if base is None else base
    streams = base.stream.unique()
    per = int(np.ceil(n_tasks / n_virtual)) + 1
    span = base.ts.max() - base.ts.min()
    parts = []
    for v in range(n_virtual):
        s = streams[v % len(streams)]
        g = base[base.stream == s]
        start = rng.integers(0, max(1, len(g) - per))
        seg = g.iloc[start:start + per].copy()
        seg["t_rel"] = seg.ts - g.ts.iloc[start] + rng.uniform(-8.64e7, 8.64e7) + 8.64e7
        seg["device_id"] = v
        parts.append(seg)
    d = pd.concat(parts).sort_values("t_rel").iloc[:n_tasks].reset_index(drop=True)
    t = d.t_rel.values - d.t_rel.values[0]
    t = t / max(t[-1], 1e-9) * (n_tasks / rate * 1000.0)
    gaps = np.diff(np.r_[0.0, t])
    d["task_id"] = np.arange(len(d))
    return d, gaps
